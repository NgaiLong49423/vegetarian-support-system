-- Generic multi-action idempotency journal for AI Assistant
CREATE TABLE AI_ASSISTANT_ACTION_JOURNAL (
    owner_id BIGINT NOT NULL,
    client_request_id UNIQUEIDENTIFIER NOT NULL,
    action_id VARCHAR(64) NOT NULL,
    tool_name VARCHAR(64) NOT NULL,
    arguments_hash CHAR(64) NOT NULL,
    state VARCHAR(16) NOT NULL,
    result_json NVARCHAR(MAX) NULL,
    error_message NVARCHAR(MAX) NULL,
    created_at DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    expires_at DATETIME2 NOT NULL DEFAULT DATEADD(day, 7, SYSUTCDATETIME()),
    CONSTRAINT PK_AI_ASSISTANT_ACTION_JOURNAL PRIMARY KEY (owner_id, client_request_id, action_id),
    CONSTRAINT FK_AI_ASSISTANT_ACTION_JOURNAL_OWNER FOREIGN KEY (owner_id) REFERENCES [USER](user_id),
    CONSTRAINT CK_AI_ASSISTANT_ACTION_JOURNAL_state CHECK (state IN ('RESERVED','WRITING','SUCCEEDED','FAILED','CANCELLED','INDETERMINATE'))
);
CREATE INDEX IX_AI_ASSISTANT_ACTION_JOURNAL_expiry ON AI_ASSISTANT_ACTION_JOURNAL(expires_at);
