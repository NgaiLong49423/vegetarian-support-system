import type { ShoppingItem } from "../api/shopping";

// Export only checklist fields; source recipes and account metadata never enter the file.
export type ShoppingExportItem = Pick<
  ShoppingItem,
  "name" | "ingredientGroup" | "quantity" | "unitCode" | "bought"
>;

/**
 * Format date as YYYYMMDD for export file name.
 */
export function getExportFileName(date: Date = new Date()): string {
  const yyyy = date.getFullYear();
  const mm = String(date.getMonth() + 1).padStart(2, "0");
  const dd = String(date.getDate()).padStart(2, "0");
  return `Danh_sach_mua_sam_${yyyy}${mm}${dd}.txt`;
}

/** Expand only the immutable meal-date names generated by FR-53, never creation timestamps. */
function mealDateHeader(listName: string): string {
  if (listName === "Danh sách cá nhân từ công thức")
    return "Nguồn: Công thức đã chọn — không gắn ngày thực đơn";
  const unknown = "Ngày thực đơn: Chưa có thông tin ngày trong danh sách này.";
  const prefix = "Danh sách mua sắm · thực đơn ";
  if (!listName.startsWith(prefix)) return unknown;
  const scope = listName.slice(prefix.length).replace(/^tuần /, "");
  const last = scope.match(/(\d{2})\/(\d{2})\/(\d{4})$/);
  if (!last) return unknown;
  const expand = (value: string) => {
    const parts = value.trim().split("/");
    if (parts.length < 1 || parts.length > 3 || parts.some(p => !/^\d+$/.test(p))) return null;
    const day = Number(parts[0]), month = Number(parts[1] ?? last[2]), year = Number(parts[2] ?? last[3]);
    const date = new Date(0);
    date.setUTCFullYear(year, month - 1, day);
    if (year < 1 || year > 9999 || date.getUTCFullYear() !== year || date.getUTCMonth() !== month - 1 || date.getUTCDate() !== day) return null;
    return `${String(day).padStart(2, "0")}/${String(month).padStart(2, "0")}/${String(year).padStart(4, "0")}`;
  };
  const range = scope.split("–");
  if (range.length === 2) {
    const first = expand(range[0]), end = expand(range[1]);
    return first && end ? `Ngày thực đơn: ${first}–${end}` : unknown;
  }
  const dates = scope.split(",").map(expand);
  return dates.length <= 7 && dates.every(Boolean)
    ? `Ngày thực đơn: ${dates.join(", ")}` : unknown;
}

/**
 * Format date as DD/MM/YYYY for text header.
 */
function formatDateHeader(date: Date = new Date()): string {
  const dd = String(date.getDate()).padStart(2, "0");
  const mm = String(date.getMonth() + 1).padStart(2, "0");
  const yyyy = date.getFullYear();
  return `${dd}/${mm}/${yyyy}`;
}

/**
 * Formats shopping list items grouped by category with [ ] and [x] check status.
 * Returns structured UTF-8 text according to FR-55 specification.
 */
export function formatShoppingListText(
  items: ShoppingExportItem[],
  exportDate: Date = new Date(),
  listName = "",
): string {
  if (items.length === 0) {
    return "";
  }

  const lines: string[] = [
    "DANH SÁCH ĐI CHỢ — MÂM XANH",
    `Ngày xuất: ${formatDateHeader(exportDate)}`,
    mealDateHeader(listName),
    "",
  ];

  // Group items by category / group
  const grouped = items.reduce<Map<string, ShoppingExportItem[]>>(
    (acc, item) => {
      const groupName = item.ingredientGroup?.trim() || "Nhóm khác";
      if (!acc.has(groupName)) acc.set(groupName, []);
      acc.get(groupName)!.push(item);
      return acc;
    },
    new Map(),
  );

  const groupNames = [...grouped.keys()];

  groupNames.forEach((groupName, index) => {
    lines.push(`[${groupName}]`);
    grouped.get(groupName)!.forEach((item) => {
      const status = item.bought ? "[x]" : "[ ]";
      const quantityStr = `: ${item.quantity.toLocaleString("vi-VN", { maximumFractionDigits: 2 })} ${item.unitCode}`;
      lines.push(`${status} ${item.name}${quantityStr}`);
    });

    // Separate groups with an empty line except for the last one
    if (index < groupNames.length - 1) {
      lines.push("");
    }
  });

  return lines.join("\n");
}

/**
 * Initiates file download with UTF-8 BOM encoding for .txt checklist.
 */
export function downloadShoppingListTxt(
  items: ShoppingExportItem[],
  exportDate: Date = new Date(),
  listName = "",
): void {
  const content = formatShoppingListText(items, exportDate, listName);
  if (!content) return;

  // Prepend \uFEFF for UTF-8 Byte Order Mark so Windows Notepad and others read accented Vietnamese properly
  const blob = new Blob([`\uFEFF${content}`], {
    type: "text/plain;charset=utf-8",
  });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement("a");
  anchor.href = url;
  anchor.download = getExportFileName(exportDate);
  try {
    document.body.appendChild(anchor);
    anchor.click();
  } finally {
    anchor.remove();
    window.setTimeout(() => URL.revokeObjectURL(url), 1000);
  }
}
